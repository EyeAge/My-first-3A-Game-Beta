import { emissive } from '../render/surfaces';
import { hex, Kit } from '../world/kit';

/** 零件箱的样件：每种基本体各用一次，改零件箱的时候拿它来看一眼有没有搭坏。 */
export function kitDemo(seed = 0) {
  const k = new Kit('kitdemo', seed);
  // 托盘：三根垫木 + 上下两层木板
  for (const z of [-0.45, 0, 0.45]) k.box('wood_pallet', 1.2, 0.09, 0.1, 0, 0.065, z, { tint: k.range(0.75, 1), grain: 'x' });
  for (let i = 0; i < 7; i++) k.box('wood_pallet', 0.1, 0.02, 1.0, -0.55 + i * 0.183, 0.12, 0, { tint: k.range(0.7, 1), grain: 'z' });
  for (const x of [-0.55, 0, 0.55]) k.box('wood_pallet', 0.1, 0.02, 1.0, x, 0.01, 0, { grain: 'z' });
  // 一只油桶（车削，带硬棱的卷边）
  k.lathe('paint_blue', [[0, 0], [0.28, 0], [0.29, 0.015], [0.29, 0.015], [0.285, 0.03], [0.285, 0.86], [0.29, 0.875], [0.29, 0.89], [0.29, 0.89], [0.27, 0.89], [0.27, 0.87], [0, 0.87]], -0.25, 0.13, 0.1, { seg: 24 });
  k.torus('steel_dark', 0.288, 0.008, -0.25, 0.43, 0.1);
  k.label('易燃', { color: 'white' }, 0.3, 0.09, [-0.25, 0.6, 0.1 + 0.287]);
  // 一个带倒角的黄色箱子、方杆护栏、圆管、软管、发光小灯
  k.box('paint_yellow', 0.4, 0.34, 0.5, 0.3, 0.3, -0.15, { c: 0.02 });
  k.bar('steel_dark', [0.08, 0.13, 0.42], [0.1, 0.9, 0.42], 0.04, 0.04, { tint: 0.8 });
  k.bar('steel_dark', [0.52, 0.13, 0.42], [0.5, 0.9, 0.42], 0.04, 0.04, { tint: 0.95 });
  k.bar('steel_dark', [0.1, 0.9, 0.42], [0.5, 0.9, 0.42], 0.04, 0.04);
  k.path('steel_galv', [[0.1, 0.5, 0.42], [0.3, 0.55, 0.46], [0.5, 0.5, 0.42]], 0.012);
  k.hose('rubber', [[0.3, 0.47, 0.1], [0.45, 0.6, 0.2], [0.55, 0.3, 0.3], [0.58, 0.13, 0.35]], 0.014);
  k.rbox('polymer_black', 0.3, 0.1, 0.3, 0.3, 0.52, -0.15, { r: 0.04 });
  k.sph('steel_bare', 0.05, 0.3, 0.62, -0.15);
  k.cyl(emissive(0x3dff6a, 3.2), 0.012, 0.01, 0.3, 0.4, 0.101, { axis: 'z', raw: true });
  k.extrude('paint_orange', [[0, 0], [0.3, 0], [0.3, 0.04], [0.04, 0.04], [0.04, 0.3], [0, 0.3]], 0.08, { pos: [-0.55, 0.13, -0.38], rot: [0, 0, 0] });
  k.strip('paint_orange', [[-0.6, 0.131, 0.3], [0.6, 0.131, 0.3]], [0, 0, 0.02], { tint: hex(0xffffff) });
  k.decal('flammable', 0.16, [0.3, 0.3, 0.101]);
  return k.finish({ surface: 'wood' });
}
