import type { Parts, V3 } from './gunmodel';

// 握枪的双手：战术手套 + 作战服袖子。坐标和枪模用同一套"图纸坐标"（毫米，[x, y, u]）。
//
// 每根手指是一串关节（掌指关节 → 两个指间关节 → 指尖），关节之间用两头粗细不同的圆台连起来，
// 关节处补一个略大的球，看起来就有指节。手背是四根掌骨并排，上面压一块硬质护指节。
// 手套是黑色皮革，虎口和掌根有一层更哑的补强，护指节和防撞条是硬橡胶。

const add = (a: V3, d: V3, k: number): V3 => [a[0] + d[0] * k, a[1] + d[1] * k, a[2] + d[2] * k];
const norm = (v: V3): V3 => { const l = Math.hypot(v[0], v[1], v[2]); return [v[0] / l, v[1] / l, v[2] / l]; };

/** 一根手指：指尖稍微粗一圈（手套指尖有一层加厚）。 */
function finger(p: Parts, pts: V3[], r: number[]) {
  const n = pts.length;
  p.limb('fabric', pts, r.map((v, i) => (i === n - 1 ? v + 0.4 : v)));
}

/**
 * 手腕往后的部分：手套的收口、魔术贴腕带、袖口、带褶皱的袖子。
 * w 是手腕中心，d 是指向手肘的方向，up 是"朝玩家眼睛的那一面"（腕带的搭扣和手表放在这一面）。
 */
function forearm(p: Parts, w: V3, d: V3, up: V3, watch: boolean) {
  d = norm(d);
  // up 去掉沿手臂方向的分量，保证它垂直于手臂
  const k = up[0] * d[0] + up[1] * d[1] + up[2] * d[2];
  up = norm([up[0] - d[0] * k, up[1] - d[1] * k, up[2] - d[2] * k]);
  p.limb('fabric', [add(w, d, -6), add(w, d, 16), add(w, d, 34)], [26, 27.5, 29]);           // 手套收口
  p.limb('strap', [add(w, d, 12), add(w, d, 27)], [29.6, 30.4], 20);                         // 腕带
  p.slab('strap', add(add(w, d, 19.5), up, 30.6), d, up, 22, 3, 17, 1.2);                    // 腕带搭扣
  p.slab('guard', add(add(w, d, 19.5), up, 32.2), d, up, 12, 1.2, 10, 0.5);                  // 搭扣上的橡胶标
  if (watch) {
    const c = add(w, d, 58);
    p.limb('strap', [add(c, d, -10), add(c, d, 10)], [31.2, 31.8], 20);                      // 表带
    p.puck('guard', add(c, up, 34), up, 20, 9, 20);                                          // 表壳
    p.puck('steel', add(c, up, 38.6), up, 21.4, 2.2, 20);                                    // 表圈
    p.puck('leather', add(c, up, 39.9), up, 16.5, 0.6, 20);                                  // 表盘
    const side = norm(cross(d, up));                                                         // 表盘上四个夜光刻度
    for (const [a, b] of [[11, 0], [-11, 0], [0, 11], [0, -11]]) p.puck('lume', add(add(add(c, up, 40.3), d, a), side, b), up, 1.7, 0.4, 8);
    for (const s of [-1, 1]) p.slab('guard', add(add(c, up, 34), norm(cross(d, up)), s * 21), d, up, 6, 5, 4, 1.2); // 按键
  }
  // 袖子：半径忽大忽小就是布料的褶皱；最前面一圈收紧的是袖口
  const start = watch ? 74 : 36;
  p.limb('sleeve', [add(w, d, start), add(w, d, start + 12)], [32.5, 33.5], 20);
  const fold = [34, 39, 36.5, 42, 39.5, 45, 43, 48, 50], at = [14, 34, 58, 86, 120, 160, 210, 280, 420];
  p.limb('sleeve', at.map((a) => add(w, d, start + a)), fold, 20);
  p.slab('strap', add(add(w, d, start + 8), up, 33.4), d, up, 15, 2, 26, 0.8);               // 袖口的调节襻
}
const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];

/** 右手：握住握把，食指伸直贴在扳机护圈外侧。 */
export function buildRightHand(p: Parts) {
  // 中指、无名指、小指：从握把右侧绕过前缘，指尖搭在左侧
  const wraps: [number, number, number][] = [[55, -66, 1], [52, -86, 0.97], [45.5, -106, 0.88]];
  const wristPts: V3[] = [[15, -92, -34], [16, -102, -37], [16, -112, -40]];
  wraps.forEach(([fu, fy, s], i) => {
    const mcp: V3 = [18, fy + 3, fu - 27];
    finger(p, [mcp, [15, fy, fu + 4], [-11, fy, fu + 6], [-16.5, fy + 3, fu - 15]], [10.4 * s, 9.5 * s, 8.8 * s, 7.9 * s]);
    p.limb('fabric', [wristPts[i], mcp], [13, 10.6 * s]);                                    // 掌骨
    p.slab('guard', [24.5, fy + 2, fu - 12], [0, 0, 1], [1, 0, 0], 16, 2.4, 9, 1);           // 指背上的防撞条
  });
  // 食指
  finger(p, [[17, -53, 36], [17.2, -47, 68], [16.6, -45, 86], [16, -44.5, 100]], [9.6, 8.6, 7.9, 7.2]);
  p.limb('fabric', [[14, -82, -30], [17, -53, 36]], [13, 10]);
  // 拇指：从虎口绕到握把左侧
  finger(p, [[8, -50, -4], [-12, -42, 20], [-16.5, -39, 40], [-17, -38, 56]], [13, 10.6, 9.4, 8.4]);
  p.limb('leather', [[2, -66, -10], [8, -92, -22]], [17, 15]);                               // 虎口和掌根
  p.slab('guard', [27.5, -78, 24], [0, 1, 0], [1, 0, 0], 62, 5, 20, 2.4);                    // 护指节
  forearm(p, [15, -104, -42], [0.28, -0.34, -0.9], [-0.6, 0.75, 0], false);
}

/** 左手：握住护木下面的垂直前握把，手背朝左，拇指贴着握把左侧朝前。手腕外侧戴着表。 */
export function buildLeftHand(p: Parts) {
  // 握把的轴线在 x=0、u=313，四指从左侧绕过前面搭到右侧，从上到下依次是食指到小指
  const ys = [-61, -80, -98, -115], scale = [1, 1, 0.96, 0.87];
  const wrists: V3[] = [[-40, -88, 256], [-42, -98, 254], [-43, -108, 254], [-43, -117, 256]];
  ys.forEach((y, i) => {
    const s = scale[i], mcp: V3 = [-21, y, 326];
    finger(p, [mcp, [11, y - 1, 336], [24.5, y - 1, 317], [17, y, 298]], [10.6 * s, 9.6 * s, 8.8 * s, 7.9 * s]);
    p.limb('fabric', [wrists[i], mcp], [12.5, 10.8 * s]);
    p.slab('guard', [-6, y - 0.5, 340.5 * (i === 3 ? 0.995 : 1)], [1, 0, 0.35], [-0.35, 0, 1], 17, 2.4, 9, 1); // 指背上的防撞条
  });
  p.slab('guard', [-31.5, -88, 318], [0, 1, 0], [-1, 0, 0.25], 66, 5, 21, 2.4);              // 护指节
  p.slab('fabric', [-41, -98, 286], [0, 1, 0], [-1, 0, -0.1], 52, 10, 44, 4.5);              // 手背
  p.slab('guard', [-46.4, -98, 286], [0, 0, 1], [-1, 0, -0.1], 26, 1.6, 30, 0.7);            // 手背上的橡胶标
  // 拇指
  finger(p, [[-31, -80, 262], [-25, -60, 290], [-21.5, -51, 312], [-17.5, -48, 332]], [14, 11.2, 9.9, 8.7]);
  p.limb('leather', [[-33, -86, 262], [-25, -70, 290]], [16, 13]);                           // 虎口
  p.slab('guard', [-32.5, -53, 301], [0, 0.35, 1], [-1, 0.5, 0], 20, 2.2, 10, 1);            // 拇指背上的防撞条
  forearm(p, [-44, -104, 250], [-0.25, -0.3, -0.92], [-0.6, 0.8, 0], true);
}
